#include "check.h"
#include "hevc_au.h"
#include "av1_obu.h"

#include <string.h>

static uint8_t stream[4096];
static size_t bytes;

static void nal(unsigned type, bool first, bool four_byte_prefix)
{
    if (four_byte_prefix) stream[bytes++] = 0;
    stream[bytes++] = 0;
    stream[bytes++] = 0;
    stream[bytes++] = 1;
    stream[bytes++] = (uint8_t)(type << 1);
    stream[bytes++] = 1;
    stream[bytes++] = first ? 0x80 : 0x40;
}

static void test_split(void)
{
    bytes = 0;
    stream[bytes++] = 0; /* Original splitter omits extra leading zero bytes. */
    nal(35, false, true);
    nal(32, false, false);
    nal(33, false, true);
    nal(34, false, false);
    nal(19, true, true);
    nal(19, false, false); /* Additional slice stays in the same picture. */
    nal(40, false, true); /* Suffix SEI stays with the picture. */
    size_t second = bytes;
    nal(39, false, true); /* Prefix SEI starts the next AU, without an AUD. */
    nal(1, true, false);
    size_t third = bytes;
    nal(32, false, true);
    nal(33, false, true);
    nal(34, false, true);
    nal(20, true, true);
    size_t fourth = bytes;
    nal(1, true, true);
    nal(36, false, true); /* EOS/EOB and trailing parameter sets are retained. */
    nal(37, false, true);
    nal(32, false, true);
    HevcAccessUnit *units = NULL;
    size_t count = 0;
    CHECK(hevc_split_access_units(stream, bytes, &units, &count));
    CHECK(count == 4);
    CHECK(units[0].offset == 1 && units[0].size == second - 1 && units[0].key);
    CHECK(units[1].offset == second && units[1].size == third - second && !units[1].key);
    CHECK(units[2].offset == third && units[2].size == fourth - third && units[2].key);
    CHECK(units[3].offset == fourth && units[3].size == bytes - fourth && !units[3].key);
    free(units);
}

static void test_key(void)
{
    for (unsigned type = 16; type <= 23; ++type) {
        for (unsigned mask = 0; mask < 8; ++mask) {
            bytes = 0;
            for (unsigned i = 0; i < 3; ++i)
                if (mask & (1u << i)) nal(32 + i, false, true);
            nal(type, true, true);
            HevcAccessUnit *units = NULL;
            size_t count = 0;
            CHECK(hevc_split_access_units(stream, bytes, &units, &count));
            CHECK(count == 1 && units[0].size == bytes);
            CHECK(units[0].key == (mask == 7 && (type == 19 || type == 20)));
            free(units);
        }
    }
}

static void bad(const uint8_t *data, size_t size)
{
    HevcAccessUnit *units = NULL;
    size_t count = 0;
    CHECK(!hevc_split_access_units(data, size, &units, &count));
    free(units);
}

static void test_bad(void)
{
    static const uint8_t no_prefix[] = {0x21, 0x43, 0x65};
    static const uint8_t leading_junk[] = {1, 0, 0, 1, 2, 1, 0x80};
    static const uint8_t short_header[] = {0, 0, 1, 2};
    static const uint8_t forbidden_bit[] = {0, 0, 1, 0x82, 1, 0x80};
    static const uint8_t zero_temporal[] = {0, 0, 1, 2, 0, 0x80};
    static const uint8_t multilayer[] = {0, 0, 1, 2, 9, 0x80};
    static const uint8_t short_slice[] = {0, 0, 1, 2, 1};
    static const uint8_t nonfirst[] = {0, 0, 1, 2, 1, 0x40};
    bad(NULL, 0);
    bad(no_prefix, sizeof(no_prefix));
    bad(leading_junk, sizeof(leading_junk));
    bad(short_header, sizeof(short_header));
    bad(forbidden_bit, sizeof(forbidden_bit));
    bad(zero_temporal, sizeof(zero_temporal));
    bad(multilayer, sizeof(multilayer));
    bad(short_slice, sizeof(short_slice));
    bad(nonfirst, sizeof(nonfirst));
    bytes = 0;
    nal(32, false, true);
    nal(33, false, true);
    bad(stream, bytes);
    bytes = 0;
    nal(19, true, true);
    nal(1, true, true);
    nal(32, false, true);
    nal(1, false, true);
    bad(stream, bytes); /* Failure after an allocated, partial AU list. */
}

/* Optional local assets provide regression coverage without downloading data. */
static void test_asset(const char *path, size_t expected, size_t key_interval)
{
    FILE *file = fopen(path, "rb");
    CHECK(file);
    CHECK(!fseek(file, 0, SEEK_END));
    long length = ftell(file);
    CHECK(length > 0 && !fseek(file, 0, SEEK_SET));
    uint8_t *data = malloc((size_t)length);
    CHECK(data && fread(data, 1, (size_t)length, file) == (size_t)length);
    fclose(file);
    HevcAccessUnit *units = NULL;
    size_t count = 0;
    CHECK(hevc_split_access_units(data, (size_t)length, &units, &count));
    CHECK(count == expected && units[0].key);
    size_t end = units[0].offset;
    for (size_t i = 0; i < count; ++i) {
        CHECK(units[i].offset == end && units[i].size > 0);
        if (key_interval) CHECK(units[i].key == (i % key_interval == 0));
        end += units[i].size;
    }
    CHECK(end == (size_t)length);
    free(units);
    free(data);
}

static void test_av1(void)
{
    /* Two 64x32 red frames, generated by libaom in low-delay mode. The
     * fixture is embedded so this test needs neither ffmpeg nor hardware. */
    static const uint8_t av1[] = {
        0x12,0x00,0x0a,0x0a,0x00,0x00,0x00,0x02,0xa7,0xff,0x36,0xbe,
        0x60,0x10,0x32,0x14,0x10,0x00,0x90,0x00,0x00,0x02,0x00,0x00,
        0x00,0x00,0xf2,0x4d,0x4f,0xc3,0xb8,0x4f,0xb1,0xd2,0xd3,0xf6,
        0x12,0x00,0x32,0x13,0x30,0x03,0x80,0x80,0x00,0x00,0x46,0xa8,
        0x80,0x00,0x02,0x40,0x00,0x00,0x80,0x00,0xdd,0x1b,0x80
    };
    LlsAccessUnit *units = NULL; size_t count = 0;
    CHECK(lls_split_access_units(LLS_CODEC_AV1, av1, sizeof(av1), &units, &count));
    CHECK(count == 2 && units[0].offset == 0 && units[0].size == 36 && units[0].key);
    CHECK(units[1].offset == 36 && units[1].size == 23 && !units[1].key);
    free(units);
    LlsAv1Sequence seq;
    CHECK(lls_av1_sequence(av1 + 4, 10, &seq));
    CHECK(seq.width == 64 && seq.height == 32 && !seq.reduced_still_picture);
    CHECK(seq.av1c[0] == 0x81 && seq.av1c[1] == 0 && seq.av1c[2] == 12 && seq.av1c[3] == 0);
    /* The same sequence with timing_info and the uvlc UINT32_MAX sentinel. */
    static const uint8_t timing[] = {
        0x04,0x00,0x00,0x00,0x04,0x00,0x00,0x00,0xf2,0x00,0x00,0x00,
        0x01,0x00,0x00,0x00,0x54,0xff,0xe6,0xd7,0xcc,0x02,0x00
    };
    CHECK(lls_av1_sequence(timing, sizeof(timing), &seq));
    CHECK(seq.width == 64 && seq.height == 32);
    uint8_t changed[sizeof(av1)]; memcpy(changed, av1, sizeof(av1));
    changed[16] = 0x30; // an inter frame carrying a sequence header is not KEY
    units = NULL; count = 0;
    CHECK(lls_split_access_units(LLS_CODEC_AV1, changed, sizeof(changed), &units, &count));
    CHECK(count == 2 && !units[0].key); free(units);
    for (unsigned kind = 0; kind < 6; ++kind) {
        memcpy(changed, av1, sizeof(av1));
        size_t length = sizeof(av1), offset = 0;
        if (kind == 0) changed[0] |= 0x80; // forbidden bit
        if (kind == 1) changed[0] &= ~2;  // missing size field
        if (kind == 2) --length;         // truncated last OBU
        if (kind == 3) { offset = 2; length -= 2; } // missing initial delimiter
        if (kind == 4) changed[4] |= 8;  // reduced header without still_picture
        if (kind == 5) changed[3] = 127; // oversized sequence OBU
        units = NULL; count = 0;
        CHECK(!lls_split_access_units(LLS_CODEC_AV1, changed + offset, length, &units, &count));
        free(units);
    }
    static const uint8_t overflow[] = {0x32,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0x7f};
    size_t cursor = 0; LlsAv1Obu obu;
    CHECK(!lls_av1_next_obu(overflow, sizeof(overflow), &cursor, &obu) && cursor == 0);
}

int main(int argc, char **argv)
{
    test_av1();
    static const uint8_t h264[] = {
        0,0,0,1,0x09,0xf0, 0,0,1,0x67,0x42,0xc0,0x1e,
        0,0,1,0x68,0xce,0x38,0x80, 0,0,1,0x65,0x80,
        0,0,1,0x65,0x40, // second slice, same picture
        0,0,1,0x41,0x80, // first slice, new picture (no AUD)
        0,0,1,0x09,0xf0, 0,0,1,0x65,0x80 // IDR without parameter sets isn't KEY
    };
    LlsAccessUnit *units = NULL;
    size_t count = 0;
    CHECK(lls_split_access_units(LLS_CODEC_H264, h264, sizeof(h264), &units, &count));
    CHECK(count == 3 && units[0].key && !units[1].key && !units[2].key);
    CHECK(units[0].size == 30 && units[1].size == 5 && units[2].size == 10);
    free(units);
    test_split();
    test_key();
    test_bad();
    if (argc == 3 || argc == 4)
        test_asset(argv[1], (size_t)strtoul(argv[2], NULL, 10),
                   argc == 4 ? (size_t)strtoul(argv[3], NULL, 10) : 0);
    else CHECK(argc == 1);
    puts("HEVC AU: ok");
    return 0;
}
